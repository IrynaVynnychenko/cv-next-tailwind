export function getServiceIdForSlug(slug: string): ServiceId | null {
  if (slug.includes('telegram')) return 'telegram-mini-apps'
  if (
    slug.includes('ai-') ||
    slug.includes('llm') ||
    slug.includes('rag') ||
    slug.includes('mcp') ||
    slug === 'how-to-automate-business-processes-with-ai'
  ) {
    return 'ai-solutions'
  }
  if (
    slug.includes('website') ||
    slug.includes('wordpress') ||
    slug.includes('webflow') ||
    slug === 'why-your-business-needs-nextjs' ||
    slug === 'why-you-need-fast-simple-website-or-blog' ||
    slug === 'react-vs-wordpress-for-business' ||
    slug === 'core-web-vitals-and-revenue'
  ) {
    return 'website-development'
  }
  if (
    slug.includes('web-application') ||
    slug.includes('saas') ||
    slug === 'how-i-would-build-a-saas' ||
    slug === 'how-i-build-mvp-and-choose-tech-stack' ||
    slug === 'scalable-nextjs-typescript-architecture' ||
    slug === 'local-first-web-applications-future-of-ux' ||
    slug === 'what-is-web-application-modern-guide'
  ) {
    return 'web-apps'
  }
  return null
}
